export interface CaseStudyImage {
  src: string
  alt: string
  /** Relative flex-grow within its row — equal images all default to 1. */
  weight?: number
  /** CSS aspect-ratio, e.g. "600 / 850". Falls back to 4/3 when omitted. */
  aspect?: string
  /** Omits the frame's violet border — for irregular die-cut PNGs with
   *  real transparency, where a rectangular stroke around the cutout
   *  looks wrong. */
  noStroke?: boolean
}

/** A row cell that's itself a small nested grid (e.g. a big image sitting
 *  beside a 2-column mini-grid of smaller shots) — for the few sections
 *  where Figma placed a multi-image cluster side-by-side with another
 *  image rather than as its own separate row. */
export interface CaseStudyImageGroup {
  weight?: number
  columns: number
  images: CaseStudyImage[]
}

export type CaseStudyCell = CaseStudyImage | CaseStudyImageGroup

export function isImageGroup(cell: CaseStudyCell): cell is CaseStudyImageGroup {
  return 'images' in cell
}

export interface CaseStudySection {
  label?: string
  /** Per-column headings (e.g. "3D Draft" / "Shooting" each over their own
   *  column) instead of one centered `label` — matches Figma sections that
   *  actually have N separate column titles in an equal-width grid, not a
   *  single merged heading. Takes priority over `label` when present. */
  columnLabels?: string[]
  /** Each inner array is one row, rendered as a flex row of `weight`-proportioned cells — mirrors the Figma source's own row/column grouping per section instead of one generic grid. */
  rows: CaseStudyCell[][]
}

export interface InkPlacement {
  ink: 1 | 2 | 3 | 4 | 5 | 6
  /** Which box `left`/`right`/`widthPct` are a % of. 'page' = the full
   *  viewport (an ink that bleeds past the Job card's own left/right edge
   *  in Figma — e.g. a raw value <7.78% or >92.22% of the 1440px canvas,
   *  which is where the card's own 112px-inset edges land there — stays
   *  pinned to the actual screen edge at any viewport width, matching
   *  every other section's own corner-bleeding ink). 'card' (default) =
   *  the 1216px card frame (`.inkFrame`) — an ink Figma placed WITHIN the
   *  card's own span, so it should scale with the card instead. */
  relativeTo?: 'page' | 'card'
  /** Exactly one of left/right, given as % of the box named by `relativeTo` — matches whichever edge the Figma source anchored to. */
  left?: number
  right?: number
  /** Exactly one of top/bottom, given as % of the page's own total height (top/bottom are always page-relative — the page has no width-style cap vertically in either Figma or the built page, so this axis never needed the page/card split). */
  top?: number
  bottom?: number
  /** % of the same box named by `relativeTo`. */
  widthPct: number
  rotateDeg?: number
  flipX?: boolean
}

export interface CaseStudy {
  slug: string
  titleLines: string[]
  heroImage: string
  heroAlt: string
  description?: string
  sections: CaseStudySection[]
  inks: InkPlacement[]
  next: string
}

